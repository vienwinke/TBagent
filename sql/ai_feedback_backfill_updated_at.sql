-- ============================================================================
-- V11 · 修正 V10 带来的"历史行假阳性"
--
-- V10 用 `ADD COLUMN updated_at ... DEFAULT CURRENT_TIMESTAMP` 加列时，MySQL 会把
-- **已有行**的 updated_at 一并填成执行时刻 —— 于是 `updated_at > created_at` 对全部
-- 历史行都成立，满意度报表里"改过评价"一栏会显示 100%（实测：32/32）。
--
-- 语义上的正确做法：**我们不知道历史行有没有被改过**，所以按"没改过"处理 ——
-- 把 updated_at 对齐到 created_at。此后 updated_at > created_at 才是真的被改过。
--
-- ⚠️ 窗口说明：本迁移会覆盖 V10 与本迁移**之间**发生的真实修改（通常只差几秒到几分钟，
--    部署时相邻执行）。若你的部署环境下这个窗口可能很长，请改为按时间阈值筛选。
-- ⚠️ 只跑一次（Flyway 保证）；手工执行请自行确认。
-- ============================================================================

UPDATE ai_feedback SET updated_at = created_at WHERE updated_at > created_at;
